def age_months_float(birth_date, measurement_date):
    if not birth_date or not measurement_date or measurement_date < birth_date:
        return 0.0
    return (measurement_date - birth_date).days / 30.4375


def interpolated_curves(table, age_months):
    age = max(0.0, min(float(age_months), 60.0))
    lo = int(floor(age))
    hi = min(lo + 1, 60)
    fraction = age - lo
    low = table.get(lo) or table[min(table)]
    high = table.get(hi) or table[max(table)]
    return {
        p: low[p] + (high[p] - low[p]) * fraction
        for p in PERCENTILES
    }


def percentile_band(value, table, age_months):
    if value is None:
        return None
    curves = interpolated_curves(table, age_months)
    value = float(value)
    if value < curves[3]:
        return "< P3"
    if value < curves[15]:
        return "P3–P15"
    if value < curves[50]:
        return "P15–P50"
    if value < curves[85]:
        return "P50–P85"
    if value < curves[97]:
        return "P85–P97"
    return "> P97"


def chart_payload(table):
    months = sorted(table)
    return {
        "months": months,
        "p3": [table[m][3] for m in months],
        "p15": [table[m][15] for m in months],
        "p50": [table[m][50] for m in months],
        "p85": [table[m][85] for m in months],
        "p97": [table[m][97] for m in months],
    }
