PERCENTILES = (3, 15, 50, 85, 97)


def _parse_table(raw):
    rows = {}
    for line in raw.strip().splitlines():
        parts = line.split()
        month = int(parts[0])
        values = [float(v) for v in parts[1:6]]
        rows[month] = dict(zip(PERCENTILES, values))
    return rows


